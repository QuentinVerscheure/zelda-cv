package zeldaCV.controller;

import zeldaCV.dto.CommentCreateDTO;
import zeldaCV.dto.CommentDTO;
import zeldaCV.dto.CommentPasswordDTO;
import zeldaCV.dto.CommentUpdateDTO;
import zeldaCV.dto.CommentVerifyResponseDTO;
import zeldaCV.service.CommentService;
import zeldaCV.util.CommentRules;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.enums.ParameterIn;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;

import java.util.List;

/**
 * Guestbook without user accounts: the visitor's browser generates a random password when creating
 * a message and keeps it in a cookie. Sending it back allows editing/deleting that message
 * for {@value zeldaCV.util.CommentRules#EDIT_WINDOW_DAYS} days.
 */
@RestController
@RequestMapping({"/api/comments"})
@Tag(name = "Comment", description = "Guestbook messages. No account needed: each message has its own password, "
        + "generated by the visitor's browser, which allows editing or deleting it for " + CommentRules.EDIT_WINDOW_DAYS + " days.")
public class CommentController {

    public static final String PASSWORD_HEADER = "X-Comment-Password";

    private final CommentService commentService;

    public CommentController(CommentService commentService) {
        this.commentService = commentService;
    }

    @GetMapping
    @Operation(summary = "Get all comments", description = "Get all the guestbook messages")
    public List<CommentDTO> getAllComments() {
        return commentService.getAllComments();
    }

    @PostMapping
    @Operation(summary = "Create a new comment",
        description = "Create a message at the given position. The password (32-128 chars among A-Z a-z 0-9 _ -) "
            + "is required to edit or delete the message later. Rate limited per IP.")
    public ResponseEntity<CommentDTO> createComment(@Valid @RequestBody CommentCreateDTO commentCreateDto) {
        CommentDTO createdCommentDto = commentService.createComment(commentCreateDto);
        return new ResponseEntity<>(createdCommentDto, HttpStatus.CREATED);
    }

    @PostMapping("/{id}/verify")
    @Operation(summary = "Check a comment's password",
        description = "Tells whether the password allows editing the message (right password and edit window still open).")
    public CommentVerifyResponseDTO verifyPassword(@PathVariable Long id, @Valid @RequestBody CommentPasswordDTO passwordDto) {
        return new CommentVerifyResponseDTO(commentService.verifyPassword(id, passwordDto.getPassword()));
    }

    @PutMapping("/{id}")
    @Operation(summary = "Update an existing comment",
        description = "Update the text and/or the position of a message. Requires its password, within "
            + CommentRules.EDIT_WINDOW_DAYS + " days after its creation.")
    public ResponseEntity<CommentDTO> updateComment(@PathVariable Long id, @Valid @RequestBody CommentUpdateDTO commentUpdateDto) {
        return ResponseEntity.ok(commentService.updateComment(id, commentUpdateDto));
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete a comment",
        description = "Delete a message. Requires its password in the " + PASSWORD_HEADER + " header, within "
            + CommentRules.EDIT_WINDOW_DAYS + " days after its creation.")
    public ResponseEntity<Void> deleteComment(
            @PathVariable Long id,
            @Parameter(in = ParameterIn.HEADER, name = PASSWORD_HEADER, required = true, description = "Password of the message")
            @RequestHeader(name = PASSWORD_HEADER, required = false) String password) {
        if (password == null || !password.matches(CommentRules.PASSWORD_PATTERN)) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, CommentRules.PASSWORD_PATTERN_MESSAGE);
        }
        commentService.deleteComment(id, password);
        return ResponseEntity.noContent().build();
    }
}
