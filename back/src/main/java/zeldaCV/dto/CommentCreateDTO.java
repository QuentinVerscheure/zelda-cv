package zeldaCV.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import zeldaCV.util.CommentRules;

@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Creation of a guestbook message")
public class CommentCreateDTO {

    @NotBlank(message = "Le pseudo est obligatoire")
    @Size(max = CommentRules.PSEUDO_MAX_LENGTH, message = "Le pseudo ne doit pas dépasser " + CommentRules.PSEUDO_MAX_LENGTH + " caractères")
    @Schema(example = "Link")
    private String pseudo;

    @NotBlank(message = "Le message est obligatoire")
    @Size(max = CommentRules.COMMENT_MAX_LENGTH, message = "Le message ne doit pas dépasser " + CommentRules.COMMENT_MAX_LENGTH + " caractères")
    @Schema(example = "Super portfolio !")
    private String comment;

    @NotNull(message = "La coordonnée X est obligatoire")
    @Schema(example = "300")
    private Integer coordinateX;

    @NotNull(message = "La coordonnée Y est obligatoire")
    @Schema(example = "250")
    private Integer coordinateY;

    @NotNull(message = "Le mot de passe est obligatoire")
    @Pattern(regexp = CommentRules.PASSWORD_PATTERN, message = CommentRules.PASSWORD_PATTERN_MESSAGE)
    @Schema(description = "Random password generated by the visitor's browser, kept in a cookie to edit/delete the message for "
            + CommentRules.EDIT_WINDOW_DAYS + " days",
            example = "q3Jf0c1x9V7mKkZb2Yw8uT4sR6pN5oLhGdEaCiBjQ0M")
    private String password;
}
